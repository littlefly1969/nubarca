"""Generate the golden set into a directory. Deterministic for pinned requirements.

Layout of the output (nothing here is committed; `results/` and the golden
directory are gitignored):

    <out>/manifest.json            dataset version, hashes, counts, disclaimer
    <out>/files/<filename>         each document in its STORED format
    <out>/layout/<doc_id>.pdf      canonical digital layout (text layer)
    <out>/pages/<doc_id>/p001-<variant>.<ext>   page images per variant
    <out>/truth/docs.jsonl         document metadata
    <out>/truth/pages.jsonl        per-page reference text, tables, formulas
    <out>/truth/queries.jsonl      queries with graded judgements
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from dataclasses import asdict
from importlib import metadata
from pathlib import Path

import pypdfium2 as pdfium
from PIL import Image
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

from .. import GENERATOR_VERSION
from .degrade import RENDER_DPI, VARIANTS, degrade
from .docs_en import DOCS_EN
from .docs_it import DOCS_IT
from .model import Doc
from .office import WRITERS
from .queries import QUERIES
from .render import render_pdf
from .truth import all_page_truths

ALL_DOCS: tuple[Doc, ...] = DOCS_IT + DOCS_EN

DISCLAIMER = (
    "SYNTHETIC golden set generated by scripts/document-bench. All people, companies, codes "
    "and amounts are fictional. Results on it are NOT a validation on any real document "
    "corpus; they rank candidates under controlled conditions only."
)

# Which page-image variant a document is stored as (what NubArca would hold).
STORED_VARIANT = {"pdf": "clean", "docx": "clean", "pptx": "clean", "xlsx": "clean",
                  "scan": "scan", "photo": "photo"}
EXT = {"clean": "png", "scan": "jpg", "photo": "jpg", "lowdpi": "png"}

PINNED = ("reportlab", "matplotlib", "pypdfium2", "pillow", "numpy", "python-docx",
          "python-pptx", "openpyxl")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def doc_by_id() -> dict[str, Doc]:
    return {d.doc_id: d for d in ALL_DOCS}


def _save(img: Image.Image, path: Path) -> None:
    if path.suffix == ".jpg":
        img.save(path, "JPEG", quality=72, optimize=False, progressive=False)
    else:
        img.save(path, "PNG", optimize=False)


def page_image_path(root: Path, doc_id: str, page: int, variant: str) -> Path:
    return root / "pages" / doc_id / f"p{page:03d}-{variant}.{EXT[variant]}"


def _image_pdf(images: list[Path], path: Path) -> None:
    """A scanned PDF: image-only pages, no text layer."""
    c = canvas.Canvas(str(path), pagesize=A4, invariant=1)
    for image in images:
        c.drawImage(ImageReader(str(image)), 0, 0, A4[0], A4[1])
        c.showPage()
    c.save()


def generate(out: Path, variants=VARIANTS, only: set[str] | None = None) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    for sub in ("files", "layout", "pages", "truth"):
        (out / sub).mkdir(exist_ok=True)
    docs = [d for d in ALL_DOCS if not only or d.doc_id in only]
    doc_rows = []
    regions: dict[tuple[str, int], list[dict]] = {}
    for doc in docs:
        layout = out / "layout" / f"{doc.doc_id}.pdf"
        for n, page_regions in render_pdf(doc, layout).items():
            regions[(doc.doc_id, n)] = page_regions
        stored = STORED_VARIANT[doc.format]
        pdf = pdfium.PdfDocument(str(layout))
        pages_dir = out / "pages" / doc.doc_id
        pages_dir.mkdir(parents=True, exist_ok=True)
        wanted = set(variants) | {stored}
        for index in range(len(pdf)):
            for variant in VARIANTS:
                if variant not in wanted:
                    continue
                bitmap = pdf[index].render(scale=RENDER_DPI[variant] / 72.0)
                img = degrade(bitmap.to_pil(), doc.doc_id, index + 1, variant)
                _save(img, page_image_path(out, doc.doc_id, index + 1, variant))
        pdf.close()

        target = out / "files" / doc.filename
        files = [doc.filename]
        if doc.format == "pdf":
            shutil.copyfile(layout, target)
        elif doc.format == "scan":
            _image_pdf([page_image_path(out, doc.doc_id, n, "scan")
                        for n in range(1, len(doc.pages) + 1)], target)
        elif doc.format == "photo":
            files = []
            for n in range(1, len(doc.pages) + 1):
                name = doc.filename if n == 1 else f"{Path(doc.filename).stem}_p{n}.jpg"
                shutil.copyfile(page_image_path(out, doc.doc_id, n, "photo"), out / "files" / name)
                files.append(name)
        else:
            WRITERS[doc.format](doc, target)
        doc_rows.append({
            "doc_id": doc.doc_id, "title": doc.title, "lang": doc.lang,
            "category": doc.category, "format": doc.format, "layout": doc.layout,
            "pages": len(doc.pages), "stored_variant": stored,
            "distractor_of": doc.distractor_of, "sheet_names": list(doc.sheet_names),
            "files": [{"name": f, "sha256": sha256_file(out / "files" / f)} for f in files],
        })

    page_rows = [asdict(t) for t in all_page_truths(docs)]
    for row in page_rows:
        row["regions"] = regions[(row["doc_id"], row["page"])]
    ids = {d.doc_id for d in docs}
    query_rows = []
    for q in QUERIES:
        rels = [asdict(r) for r in q.rels if r.doc in ids]
        if q.rels and not rels:
            continue
        query_rows.append({"qid": q.qid, "text": q.text, "lang": q.lang, "types": list(q.types),
                           "rels": rels, "answer": q.answer, "visual_only": q.visual_only,
                           "answerable": q.answerable})
    truth = out / "truth"
    for name, rows in (("docs", doc_rows), ("pages", page_rows), ("queries", query_rows)):
        with (truth / f"{name}.jsonl").open("w", encoding="utf-8") as handle:
            for row in rows:
                handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")

    truth_hash = hashlib.sha256()
    for name in ("docs", "pages", "queries"):
        truth_hash.update((truth / f"{name}.jsonl").read_bytes())
    content_hash = hashlib.sha256()
    for path in sorted(p for p in out.rglob("*") if p.is_file() and p.name != "manifest.json"):
        content_hash.update(path.relative_to(out).as_posix().encode())
        content_hash.update(sha256_file(path).encode())

    type_counts: dict[str, int] = {}
    for row in query_rows:
        for t in row["types"]:
            type_counts[t] = type_counts.get(t, 0) + 1
    manifest = {
        "dataset": "nubarca-document-golden",
        "generator_version": GENERATOR_VERSION,
        "dataset_version": f"{GENERATOR_VERSION}+{truth_hash.hexdigest()[:12]}",
        "truth_sha256": truth_hash.hexdigest(),
        "content_sha256": content_hash.hexdigest(),
        "synthetic": True,
        "disclaimer": DISCLAIMER,
        "variants": sorted(set(variants)),
        "counts": {
            "documents": len(doc_rows),
            "pages": len(page_rows),
            "queries": len(query_rows),
            "answerable": sum(1 for r in query_rows if r["answerable"]),
            "visual_only": sum(1 for r in query_rows if r["visual_only"]),
            "by_type": dict(sorted(type_counts.items())),
            "by_format": {f: sum(1 for d in doc_rows if d["format"] == f)
                          for f in sorted({d["format"] for d in doc_rows})},
        },
        "libraries": {name: _version(name) for name in PINNED},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    return manifest


def _version(name: str) -> str:
    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        return "missing"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--variants", default=",".join(VARIANTS))
    parser.add_argument("--only", default="", help="comma-separated doc ids (debugging)")
    args = parser.parse_args(argv)
    only = {x for x in args.only.split(",") if x} or None
    manifest = generate(args.out, tuple(v for v in args.variants.split(",") if v), only)
    print(json.dumps({k: manifest[k] for k in ("dataset_version", "content_sha256")}, indent=2))
    print(json.dumps(manifest["counts"], indent=2, ensure_ascii=False))
    return 0
